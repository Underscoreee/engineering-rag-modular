"""Vendor-neutral structured generation DTOs and an explicit validation boundary."""

import json
from typing import Annotated, Literal, TypeVar

from pydantic import BaseModel, Field, JsonValue, StrictInt, model_validator

from .common import ContractModel, NonEmptyStr, TraceContext

OutputModel = TypeVar("OutputModel", bound=BaseModel)
TokenCount = Annotated[StrictInt, Field(ge=0)]


class StructuredLLMConfig(ContractModel):
    """An application-selected model configuration, without credentials or SDK options."""

    config_id: NonEmptyStr
    model_id: NonEmptyStr
    model_revision: NonEmptyStr | None = None
    temperature: Annotated[float, Field(ge=0, le=2, allow_inf_nan=False)] = 0
    timeout_seconds: Annotated[float, Field(gt=0, allow_inf_nan=False)]
    max_output_tokens: Annotated[StrictInt, Field(gt=0)]


class StructuredLLMRequest(ContractModel):
    schema_version: Literal["1.0"] = "1.0"
    request_id: NonEmptyStr
    stage: NonEmptyStr
    input: dict[str, JsonValue]
    output_schema: dict[str, JsonValue]
    config: StructuredLLMConfig
    trace: TraceContext | None = None

    @model_validator(mode="after")
    def validate_json_content(self) -> "StructuredLLMRequest":
        json.dumps(self.input, allow_nan=False)
        json.dumps(self.output_schema, allow_nan=False)
        return self


class LLMTokenUsage(ContractModel):
    input_tokens: TokenCount | None = None
    output_tokens: TokenCount | None = None
    total_tokens: TokenCount | None = None

    @model_validator(mode="after")
    def validate_total(self) -> "LLMTokenUsage":
        counts = (self.input_tokens, self.output_tokens, self.total_tokens)
        if all(count is not None for count in counts):
            assert self.input_tokens is not None and self.output_tokens is not None
            if self.total_tokens != self.input_tokens + self.output_tokens:
                raise ValueError("total_tokens must equal input_tokens plus output_tokens")
        return self


class StructuredLLMResponse(ContractModel):
    """Transport data only: constructing this DTO does not validate business output."""

    schema_version: Literal["1.0"] = "1.0"
    request_id: NonEmptyStr
    model_id: NonEmptyStr
    model_revision: NonEmptyStr | None = None
    data: dict[str, JsonValue]
    usage: LLMTokenUsage | None = None
    provider_request_id: NonEmptyStr | None = None

    @model_validator(mode="after")
    def validate_json_content(self) -> "StructuredLLMResponse":
        json.dumps(self.data, allow_nan=False)
        return self

    def validate_output(
        self, request: StructuredLLMRequest, output_model: type[OutputModel]
    ) -> OutputModel:
        """Bind response to request, then validate with the caller's Pydantic schema.

        Arbitrary external JSON Schema is not interpreted here. The authoritative
        schema must be generated by the exact application-supplied output model.
        Factual grounding and metadata matching remain the caller's responsibility.
        """

        request = StructuredLLMRequest.model_validate(request.model_dump(mode="python"))
        validated = type(self).model_validate(self.model_dump(mode="python"))
        if validated.request_id != request.request_id:
            raise ValueError("LLM response request_id mismatch")
        if validated.model_id != request.config.model_id:
            raise ValueError("LLM response model_id mismatch")
        if (
            request.config.model_revision is not None
            and validated.model_revision != request.config.model_revision
        ):
            raise ValueError("LLM response model_revision mismatch")
        if request.output_schema != output_model.model_json_schema():
            raise ValueError("output model does not match request.output_schema")
        if output_model.model_config.get("extra") != "forbid":
            raise ValueError("structured output model must forbid extra fields")
        return output_model.model_validate_json(
            json.dumps(validated.data, ensure_ascii=False, allow_nan=False), strict=True
        )
